export function sortMatchingSchools(schools, selectedKeys) {
  const fieldsInOrder=[...new Set(selectedKeys.map(key=>key.split('|')[0]))];
  const first=fieldsInOrder[0];
  const priority=(id,field)=>{const list=schoolOrder[field]||generalSchoolOrder;const i=list.indexOf(id);return i>=0?i:generalSchoolOrder.indexOf(id)>=0?list.length+generalSchoolOrder.indexOf(id):999;};
  return [...schools].sort((a,b)=>{
    const coverFirst=Number(b.programs.some(m=>m.field===first))-Number(a.programs.some(m=>m.field===first));
    if(coverFirst)return coverFirst;
    for(const field of fieldsInOrder) {
      const aHas=a.programs.some(m=>m.field===field),bHas=b.programs.some(m=>m.field===field);
      if(aHas!==bHas)return aHas?-1:1;
      if(aHas){const diff=priority(a.id,field)-priority(b.id,field);if(diff)return diff;}
    }
    return priority(a.id,first)-priority(b.id,first)||a.name.localeCompare(b.name,'vi');
  });
}
export function majorChoices(majors) {
  const choices = new Map();
  for (const major of majors) {
    const key = majorChoiceKey(major);
    if (!choices.has(key)) choices.set(key,{key,name:major.name,field:major.field,holland:major.holland,universities:new Set()});
    choices.get(key).universities.add(major.universityId);
  }
  return [...choices.values()].map(choice=>({...choice,universities:[...choice.universities]}));
}
