export function combinationScores(values) {
  return Object.entries(combinations)
    .flatMap(([code, keys]) =>
      keys.every(
        (key) =>
          typeof values[key] === "number" && Number.isFinite(values[key]),
      )
        ? [
            {
              code,
              subjects: keys,
              total:
                Math.round(
                  keys.reduce((sum, key) => sum + values[key], 0) * 100,
                ) / 100,
            },
          ]
        : [],
    )
    .sort((a, b) => b.total - a.total || a.code.localeCompare(b.code));
}
export function calculateResult(questions, answers) {
  const scores = Object.fromEntries(Object.keys(groups).map((key) => [key, 0]));
  for (const question of questions) {
    const value = answers[question.id];
    if (!Number.isInteger(value) || value < 1 || value > 5)
      throw new Error("Vui lòng trả lời đủ các câu hỏi với mức từ 1 đến 5.");
    scores[question.group] += value;
  }
  const order = Object.keys(groups).sort((a, b) => scores[b] - scores[a]);
  const tie = order.some(
    (key, index) => index > 0 && scores[key] === scores[order[index - 1]],
  );
  return {
    scores,
    code: order.slice(0, 3).join(""),
    tie,
    uniform: new Set(Object.values(scores)).size === 1,
  };
}
export function interestFit(scores, code) {
  if (!scores) return null;
  // Editorial mapping, NOT a probability of success/admission. Neutral answers => 50.
  const weights = [3, 2, 1];
  return Math.round(
    ([...code].reduce(
      (sum, key, index) => sum + ((scores[key] - 10) / 40) * weights[index],
      0,
    ) /
      6) *
      100,
  );
}
// Only a school's explicitly published 2026 /30 THPT cutoff (or official THPT-equivalent)
// participates in sorting. Never scale /100 or /1200 scores to /30 ourselves.
export function thptSortingScore(major) {
  return (
    major.admissionScores?.find(
      (score) =>
        score.year === 2026 &&
        score.scale === 30 &&
        ["thpt", "thpt-equivalent"].includes(score.method) &&
        Number.isFinite(score.value),
    ) ?? null
  );
}
export function compositeSortingScore(major) {
  return (
    major.admissionScores?.find(
      (score) =>
        score.year === 2026 &&
        score.scale === 100 &&
        score.method === "composite" &&
        Number.isFinite(score.value),
    ) ?? null
  );
}
export function admissionGroup(major) {
  // A /30 equivalence published for the SAME composite method (HCMUS) is not a separate THPT route.
  if (
    major.admissionScores?.some(
      (score) => score.method === "composite" && score.year === 2026,
    )
  )
    return "composite";
  if (thptSortingScore(major)) return "thpt";
  return "unverified";
}
export function comparableAnnualTuition(major) {
  const tuition = major.tuition;
  return tuition &&
    ["năm", "năm học"].includes(tuition.period) &&
    !tuition.approximate &&
    tuition.year !== "2025–2026" &&
    Number.isFinite(tuition.value)
    ? tuition.value
    : null;
}
export function matchesSchoolFilter(school,filter) {
  if(!filter)return true;
  if(filter==='area:hcm')return school.province==='TP. Hồ Chí Minh';
  if(filter.startsWith('type:'))return school.institutionType===filter.slice(5);
  return school.system===filter;
}
