export function matchesHolland(major, code) {
  // Editorial mapping: prioritize the strongest group and one more from the top three.
  // No field is C-led in this curated catalog, so allow C anywhere to avoid an empty result.
  return Boolean(
    code &&
    (major.holland[0] === code[0] ||
      (code[0] === "C" && major.holland.includes("C"))) &&
    [...code].filter((group) => major.holland.includes(group)).length >= 2,
  );
}
export function sortCatalogMajors(majors, sort, mode = "thpt") {
  const byName = (a, b) =>
    a.name.localeCompare(b.name, "vi") || a.id.localeCompare(b.id);
  const byCutoff = (a, b, direction) => {
    const x =
      (mode === "composite" ? compositeSortingScore(a) : thptSortingScore(a))
        ?.value ?? null;
    const y =
      (mode === "composite" ? compositeSortingScore(b) : thptSortingScore(b))
        ?.value ?? null;
    if (x === null || y === null)
      return x === null && y === null ? byName(a, b) : x === null ? 1 : -1;
    return direction * (x - y) || byName(a, b);
  };
  return [...majors].sort((a, b) => {
    if (mode === "composite") {
      const school = a.universityId.localeCompare(b.universityId);
      if (school) return school; // Never compare composite cutoff values between schools.
    }
    if (sort === "cutoff-desc") return byCutoff(a, b, -1);
    if (sort === "cutoff-asc") return byCutoff(a, b, 1);
    if (sort === "holland-cutoff-desc")
      return (b.fit ?? -1) - (a.fit ?? -1) || byCutoff(a, b, -1);
    if (sort === "holland-cutoff-asc")
      return (b.fit ?? -1) - (a.fit ?? -1) || byCutoff(a, b, 1);
    if (sort === "fit")
      return (b.fit ?? -1) - (a.fit ?? -1) || byCutoff(a, b, -1);
    if (sort === "tuition")
      return (
        (comparableAnnualTuition(a) ?? Infinity) -
          (comparableAnnualTuition(b) ?? Infinity) || byName(a, b)
      );
    return byName(a, b);
  });
}
