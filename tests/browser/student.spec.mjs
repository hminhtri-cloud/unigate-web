async function setSchoolFilter(page,group,choice='') {
  choice=({'Tất cả trường tại TP.HCM':'TP.HCM','Công':'Trường công','Trường tư':'Tư thục','Tư':'Tư thục'})[choice]||choice;
  await page.getByRole('button',{name:'Nhóm trường',exact:true}).click();
  const options=page.getByRole('group',{name:group,exact:true});
  while(await options.locator('input:checked').count())await options.locator('input:checked').first().uncheck();
  if(choice)await options.getByRole('checkbox',{name:choice}).check();
  await page.getByRole('button',{name:'Xong',exact:true}).click();
}
async function setCombinations(page,label,codes=[]) {
  await page.getByRole('button',{name:label,exact:true}).click();
  const options=page.getByRole('dialog',{name:label,exact:true}).getByRole('group');
  while(await options.locator('input:checked').count())await options.locator('input:checked').first().uncheck();
  for(const code of codes)await options.getByRole('checkbox',{name:new RegExp(`^${code}(?:\\s|$)`)}).check();
  await page.getByRole('button',{name:'Xong',exact:true}).click();
}
